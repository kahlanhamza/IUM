#!/usr/bin/env python3
"""Cross-session verification: the vectors the previous session pinned in
scripts/quickxor_vectors.txt (generated by scripts/quickxor_ref.py, then
cross-checked 12/12 against the PyPI quickxorhash package) must ALSO come out
of THIS session's independent three-implementation module
(scripts/quickxorhash.py — slot/ring/naive, verified 105/105 against rclone's
official vector suite). Two independent derivation paths, one vector set.
"""
import base64
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from quickxorhash import quick_xor_hash_slot  # noqa: E402

VECTORS = Path("/home/z/my-project/scripts/quickxor_vectors.txt")


def pattern(n: int) -> bytes:
    return bytes(i % 251 for i in range(n))


def input_for(name: str) -> bytes:
    if name == "empty":
        return b""
    if name == "one-byte-a":
        return b"a"
    if name == "three-byte-abc":
        return b"abc"
    if name == "63B":
        return pattern(63)
    if name == "64B":
        return pattern(64)
    if name == "65B":
        return pattern(65)
    if name == "159B":
        return pattern(159)
    if name == "160B":
        return pattern(160)
    if name == "161B":
        return pattern(161)
    if name == "600B":
        return pattern(600)
    if name == "1MiB":
        return pattern(1024 * 1024)
    if name == "5MiB":
        return pattern(5 * 1024 * 1024)
    raise ValueError(f"unknown vector name {name}")


def main() -> None:
    ok = 0
    fails = []
    for line in VECTORS.read_text().splitlines():
        if not line.strip():
            continue
        name, want = line.split("\t")
        got = quick_xor_hash_slot(input_for(name))
        if base64.b64encode(got).decode() == want:
            ok += 1
        else:
            fails.append((name, want, base64.b64encode(got).decode()))
    print(f"cross-session check: {ok}/12 vectors reproduced by the independent implementation")
    for name, want, got in fails:
        print(f"  FAIL {name}: {got} != {want}")
    if fails:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
