#[test]
fn quick_xor_hash_matches_official_algorithm_vectors() {
    // every vector cross-checked 12/12 against the independent PyPI
    // `quickxorhash` implementation (see the module doc comment)
    assert_eq!(quick_xor_hash(&[]), "AAAAAAAAAAAAAAAAAAAAAAAAAAA=");
    assert_eq!(quick_xor_hash(b"a"), "YQAAAAAAAAAAAAAAAQAAAAAAAAA=");
    assert_eq!(quick_xor_hash(b"abc"), "YRDDGAAAAAAAAAAAAwAAAAAAAAA=");
    // 63/64/65: byte-class boundaries
    assert_eq!(quick_xor_hash(&pattern(63)), "IIWmsFixF8Jepry6bmIWXogPBG4=");
    assert_eq!(quick_xor_hash(&pattern(64)), "IIWmsFix98Vepry6EWIWXogPBG4=");
    assert_eq!(quick_xor_hash(&pattern(65)), "IIWmsFix98Uepry6EGIWXogPBG4=");
    // 159/160/161: the 160-bit shift-cycle boundary
    assert_eq!(
        quick_xor_hash(&pattern(159)),
        "/+EGLlnQi0dVs5OEknWhEnz5Ih0="
    );
    assert_eq!(
        quick_xor_hash(&pattern(160)),
        "/+EGLlnQi0dVs5OErXWhEnz5wg4="
    );
    assert_eq!(
        quick_xor_hash(&pattern(161)),
        "X+EGLlnQi0dVs5OErHWhEnz5wg4="
    );
    // multi-shift-cycle (600 B covers 3 cycles + 120)
    assert_eq!(
        quick_xor_hash(&pattern(600)),
        "z0rVUrguclftJj1osaWH0yosV44="
    );
    // 1 MiB and 5 MiB patterned data
    assert_eq!(
        quick_xor_hash(&pattern(1024 * 1024)),
        "pVcWCkWK/HTa4DMyE2B1A1Y9XyM="
    );
    assert_eq!(
        quick_xor_hash(&pattern(5 * 1024 * 1024)),
        "/p/DCDFbDO0I+W4Z5OEzEr6u56Q="
    );
}

#[test]
fn quick_xor_hash_streaming_matches_one_shot() {
    // the adapter hashes fragments as they stream — the streaming state must
    // survive arbitrary HashCore-call boundaries (the C# contract: shiftSoFar
    // advances once per call, by shift * (cbSize % 160))
    use ium_core::onedrive::QuickXorHasher;

    let data = pattern(5 * 1024 * 1024);
    let one_shot = quick_xor_hash(&data);

    // chunked at 5 MiB / 700 KiB / odd 7-byte splits / the 320 KiB geometry
    for chunk_len in [5 * 1024 * 1024, 700 * 1024, 327_680, 7, 1] {
        let mut h = QuickXorHasher::new();
        for chunk in data.chunks(chunk_len) {
            h.update(chunk);
        }
        assert_eq!(
            h.finalize(),
            one_shot,
            "streaming diverged at chunk_len={chunk_len}"
        );
    }
}

#[test]
fn adapter_registers_as_onedrive_and_is_resumable_only() {
    let cfg = ium_core::onedrive::OneDriveConfig::from_parts(
        r#"{"access_token":"a","refresh_token":"r","expires_in":4500}"#,
    )
    .expect("a real token shape parses");
    let a = OneDriveAdapter::new(cfg);
    assert_eq!(a.name(), "onedrive");
    let cap = a.capabilities();
    // Upload-session resume yes; no dynamic chunks (every fragment except the
    // last is a 320 KiB multiple — prescribed geometry), no tail-race (the
    // final fragment's PUT is the atomic commit).
    assert!(cap.has(ium_core::adapter::Capability::RESUMABLE));
    assert!(!cap.has(ium_core::adapter::Capability::DYNAMIC_CHUNKS));
    assert!(!cap.has(ium_core::adapter::Capability::TAIL_RACE));
    // prescribed geometry: planned chunks 5 MiB, and the Graph hard rule —
    // the planned size is a multiple of 320 KiB (#56 channel).
    assert_eq!(a.uniform_block(), Some(5 * 1024 * 1024));
    assert_eq!(a.uniform_block().unwrap() % 327_680, 0);
}
