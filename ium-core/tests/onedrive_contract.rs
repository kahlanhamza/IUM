use ium_core::adapter::TransferAdapter;
use ium_core::onedrive::{quick_xor_hash, redirect_uri, OneDriveAdapter, REDIRECT_PORT, SCOPE};

/// data[i] = (i % 251) as u8 — mirrors scripts/quickxor_ref.py.
fn pattern(len: usize) -> Vec<u8> {
    (0..len).map(|i| (i % 251) as u8).collect()
}

#[test]
fn redirect_port_is_fixed_8739() {
    assert_eq!(REDIRECT_PORT, 8739);
    assert_eq!(redirect_uri(), "http://localhost:8739");
    // the app identity is a PUBLIC identifier (no secret exists on the lane)
    assert_eq!(
        ium_core::onedrive::CLIENT_ID,
        "c3a906be-d85b-4409-b3cd-bc152ae58550"
    );
}

#[test]
fn scope_pins_offline_access_and_full_drive() {
    // the lane's scope-trim trap: without `offline_access` Entra issues NO
    // refresh token at all — the lane dies at the first access-token expiry.
    // `Files.ReadWrite` is the full-drive scope (no App-Folder analogue); the
    // shell surfaces the destination folder to the user at connect time.
    assert!(
        SCOPE.contains("offline_access"),
        "no offline_access => Entra issues NO refresh token at all"
    );
    assert!(SCOPE.contains("Files.ReadWrite"));
}

